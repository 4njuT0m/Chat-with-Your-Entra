"""Stage 3 - Let the agent run a full audit and save the report as Markdown.

Run from the repo folder:
    python src\\audit_report.py                      # saves reports/baseline-report.md
    python src\\audit_report.py entragoat-report     # saves reports/entragoat-report.md
"""

import sys
from datetime import date
from pathlib import Path

from agent import SYSTEM_PROMPT, ask
from checks import run_checks

REPORTS_DIR = Path(__file__).resolve().parent.parent / "reports"

REPORT_REQUEST = """Run a full security audit of the tenant with run_security_checks (check = all).
Write the result as a Markdown report:
1. A short summary table: Finding | Severity | Status | MITRE ATT&CK (technique IDs)
2. One section per failed finding, in the finding format from your instructions
3. One line listing the checks that passed
Use only the tool results. Do not add anything that is not in the evidence.
Do not add a title, the report already has one."""

name = sys.argv[1] if len(sys.argv) > 1 else "baseline-report"
messages = [
    {"role": "system", "content": SYSTEM_PROMPT},
    {"role": "user", "content": REPORT_REQUEST},
]

print("Running audit, this can take a minute...")
report = ask(messages)

REPORTS_DIR.mkdir(exist_ok=True)
path = REPORTS_DIR / f"{name}.md"
# Severity count is done in Python, not by the AI, so the numbers are exact
failed = [f for f in run_checks() if f["status"] in ("FAIL", "WARN")]
counts = {s: sum(1 for f in failed if f["severity"] == s) for s in ("High", "Medium", "Low")}
summary = f"Failed checks: {len(failed)} (High: {counts['High']}, Medium: {counts['Medium']}, Low: {counts['Low']})"
header = (
    f"# Entra ID audit report\n\nTenant: Contoso (Pearson lab)  \nDate: {date.today()}  \n"
    f"Generated by: Chat with Your Entra agent  \n{summary}\n\n"
)
path.write_text(header + report + "\n", encoding="utf-8")
print(f"Saved: {path}")
